"""
Generate training data: run target model on prompts to create responses.

This produces (prompt, target_response) pairs matching DFlash's training recipe.
Responses are generated by the target model to ensure distribution alignment.

Usage:
    modal run scripts/generate_data.py
"""

import modal
from pathlib import Path

app = modal.App("midas-generate-data")

model_volume = modal.Volume.from_name("llm-weights", create_if_missing=True)
data_volume = modal.Volume.from_name("midas-training-data", create_if_missing=True)

PROJECT_ROOT = Path(__file__).parent.parent

image = (
    modal.Image.debian_slim(python_version="3.11")
    .pip_install(
        "torch>=2.2.0",
        "transformers>=4.57.0",
        "accelerate",
        "datasets",
        "numpy",
        "tqdm",
        "loguru",
        "huggingface_hub",
    )
)


@app.function(
    image=image,
    gpu="A100-40GB",
    volumes={
        "/models": model_volume,
        "/data": data_volume,
    },
    secrets=[modal.Secret.from_name("huggingface")],
    timeout=86400,
)
def generate_training_data(
    num_samples: int = 800_000,
    max_new_tokens: int = 512,
    batch_size: int = 32,
):
    """
    Generate training data by running target model on prompts.

    1. Load prompts from instruction-following datasets
    2. Run Qwen3-4B to generate responses
    3. Save (prompt, response) pairs as jsonl
    """
    import json
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from datasets import load_dataset
    from tqdm import tqdm
    from loguru import logger

    device = torch.device("cuda")
    output_path = Path("/data/training_sequences.jsonl")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Load target model
    logger.info("Loading Qwen3-4B for response generation...")
    model = AutoModelForCausalLM.from_pretrained(
        "/models/Qwen3-4B",
        torch_dtype=torch.bfloat16,
        device_map=device,
    )
    model.eval()
    tokenizer = AutoTokenizer.from_pretrained("/models/Qwen3-4B")
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"

    # Load prompts from the EXACT datasets DFlash used (paper Section 5):
    # "800K samples from NVIDIA Nemotron Post-Training Dataset V2 and CodeAlpaca"
    # "Instead of directly using the original dataset, we construct our training
    #  set with the responses generated by the target model"
    logger.info("Loading prompts from Nemotron-Post-Training-Dataset-v2 + CodeAlpaca...")
    prompts = []
    target_nemotron = int(num_samples * 0.8)  # 80% from Nemotron, 20% CodeAlpaca
    target_code = num_samples - target_nemotron

    # Nemotron Post-Training Dataset V2 (gated, requires HF login)
    # Splits: stem, chat, math, code, multilingual_*
    # We use the English splits matching DFlash's diverse training mix
    nemotron_splits = ["math", "code", "stem", "chat"]
    per_split = target_nemotron // len(nemotron_splits)

    for split_name in nemotron_splits:
        try:
            ds = load_dataset(
                "nvidia/Nemotron-Post-Training-Dataset-v2",
                split=split_name,
                streaming=True,
            )
            count = 0
            for sample in ds:
                if count >= per_split:
                    break
                # Nemotron format: messages list with role/content
                messages = sample.get("messages", [])
                prompt = None
                for msg in messages:
                    if msg.get("role") == "user":
                        prompt = msg.get("content", "")
                        break

                if prompt and len(prompt.strip()) > 20:
                    prompts.append(prompt.strip())
                    count += 1

            logger.info(f"Loaded {count} prompts from Nemotron/{split_name}")
        except Exception as e:
            logger.warning(f"Could not load Nemotron/{split_name}: {e}")
            logger.warning("Make sure you have accepted the dataset license on HuggingFace")

    # CodeAlpaca-20k (public, code instructions)
    try:
        ds = load_dataset("sahil2801/CodeAlpaca-20k", split="train", streaming=True)
        count = 0
        for sample in ds:
            if count >= target_code:
                break
            instruction = sample.get("instruction", "")
            if instruction and len(instruction.strip()) > 20:
                prompts.append(instruction.strip())
                count += 1
        logger.info(f"Loaded {count} prompts from CodeAlpaca-20k")
    except Exception as e:
        logger.warning(f"Could not load CodeAlpaca: {e}")

    logger.info(f"Total prompts: {len(prompts)}")
    prompts = prompts[:num_samples]

    # Check for existing progress (resume support)
    existing_count = 0
    if output_path.exists():
        with open(output_path) as f:
            existing_count = sum(1 for _ in f)
        logger.info(f"Found {existing_count} existing samples, resuming from there")

    # Skip prompts we've already processed
    start_idx = existing_count * batch_size // max(1, existing_count // (existing_count or 1))
    # Simpler: just skip proportional number of prompts
    prompts_to_process = prompts[existing_count:]

    # Generate responses with target model
    logger.info(f"Generating {len(prompts_to_process)} responses with Qwen3-4B...")
    generated = existing_count

    with open(output_path, "a") as f:  # append mode for resume support
        for i in tqdm(range(0, len(prompts_to_process), batch_size), desc="Generating"):
            batch_prompts = prompts_to_process[i : i + batch_size]

            # Tokenize prompts
            inputs = tokenizer(
                batch_prompts,
                padding=True,
                truncation=True,
                max_length=1024,
                return_tensors="pt",
            ).to(device)

            # Generate responses with greedy decoding (deterministic, matches eval setting)
            with torch.no_grad():
                outputs = model.generate(
                    **inputs,
                    max_new_tokens=max_new_tokens,
                    do_sample=False,
                    pad_token_id=tokenizer.pad_token_id,
                )

            # Decode and save
            for j, (prompt, output_ids) in enumerate(zip(batch_prompts, outputs)):
                # Get only the generated part (after the prompt)
                prompt_len = inputs["input_ids"][j].shape[0]
                response_ids = output_ids[prompt_len:]
                response = tokenizer.decode(response_ids, skip_special_tokens=True)

                if len(response.strip()) > 10:
                    record = {
                        "prompt": prompt,
                        "response": response,
                        "full_text": f"{prompt}\n{response}",
                    }
                    f.write(json.dumps(record) + "\n")
                    generated += 1

            # Commit every 500 batches (~4000 samples) to persist progress
            if (i // batch_size) % 500 == 0 and i > 0:
                f.flush()
                data_volume.commit()
                logger.info(f"Committed {generated} samples to volume")

    data_volume.commit()
    logger.info(f"Done! Generated {generated} total training sequences at {output_path}")


@app.local_entrypoint()
def main(num_samples: int = 100_000):
    generate_training_data.remote(num_samples=num_samples)
    print("Data generation complete!")
    print("Training data saved to midas-training-data volume.")
    print("Next: modal run scripts/modal_train.py")
